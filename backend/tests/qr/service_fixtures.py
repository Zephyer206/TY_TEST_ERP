def create_service_fixture(connection):
    # Only old-domain prerequisite tables are created from metadata. All new
    # product-box tables are created by the real frozen migration below.
    old_tables = {c.__table__ for c in (User, Customer, Machine, Part, ProductionPlan,
                  PlanMachineAssignment, AuditLog, MaterialBatch, MaterialBatchChild,
                  BatchTransaction, Material, Supplier, ProductionSession, Inventory)}
    while True:
        expanded = old_tables | {fk.column.table for table in old_tables for fk in table.foreign_keys}
        if expanded == old_tables:
            break
        old_tables = expanded
    assert not ({t.name for t in old_tables} & {t.name for t in m.DOMAIN_TABLES})
    Base.metadata.create_all(connection, tables=[t for t in Base.metadata.sorted_tables if t in old_tables])
    connection.execute(text("DO $$ BEGIN CREATE TYPE scantype AS ENUM ('MAT','MCN','PFC','PRT'); "
                            "EXCEPTION WHEN duplicate_object THEN NULL; END $$"))
    connection.execute(text("DO $$ BEGIN CREATE TYPE scanoperation AS ENUM ('QUERY','SPLIT','CONSUME','REPORT','INBOUND'); "
                            "EXCEPTION WHEN duplicate_object THEN NULL; END $$"))
    connection.execute(text("""CREATE TABLE qr_scan_logs (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scan_type scantype NOT NULL, entity_id integer NOT NULL,
        entity_no varchar(100), operator_id integer REFERENCES users(id),
        operation scanoperation NOT NULL, notes text,
        scanned_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP)"""))
    run_migration(connection, "upgrade")


