"""Protected PostgreSQL fixtures: never run test DDL/DML in the business database.

Only the existing connection is consumed internally. No URLs or credentials are
printed or written. Each temporary database has a random name and its original
OID is checked before teardown; other databases cannot be dropped by this helper.
"""
from __future__ import annotations

import importlib.util
import re
from contextlib import contextmanager
from pathlib import Path
from uuid import uuid4

import pytest
from alembic.migration import MigrationContext
from alembic.operations import Operations
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.pool import NullPool

from app.core.config import settings

ROOT = Path(__file__).resolve().parents[3]
MIGRATION_PATH = ROOT / "alembic/versions/20261022_product_box_foundation.py"
LEGACY_TABLES = ("users", "parts", "customers", "machines", "material_batches",
                 "production_plans", "plan_machine_assignments")


def load_migration():
    spec = importlib.util.spec_from_file_location("qr_foundation_revision", MIGRATION_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_migration(connection, direction):
    with Operations.context(MigrationContext.configure(connection)):
        getattr(load_migration(), direction)()


def create_legacy_fixture(connection, *, native_enums=True):
    """Small prerequisite schema, not a replay of unrelated historical migrations.

    Includes an existing material/QR record, so additive compatibility is observed
    against persisted old data rather than only an empty metadata schema.
    """
    for name in LEGACY_TABLES:
        connection.execute(text(f'CREATE TABLE "{name}" (id integer PRIMARY KEY)'))
        connection.execute(text(f'INSERT INTO "{name}" (id) VALUES (1),(2)'))
    if native_enums:
        connection.execute(text("CREATE TYPE scantype AS ENUM ('MAT','MCN','PFC','PRT')"))
        connection.execute(text("CREATE TYPE scanoperation AS ENUM ('QUERY','SPLIT','CONSUME','REPORT','INBOUND')"))
    scan_type = "scantype" if native_enums else "varchar(20)"
    operation = "scanoperation" if native_enums else "varchar(20)"
    connection.execute(text(f"""CREATE TABLE qr_scan_logs (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scan_type {scan_type} NOT NULL, entity_id integer NOT NULL,
        entity_no varchar(100), operator_id integer REFERENCES users(id),
        operation {operation} NOT NULL, notes text,
        scanned_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP)"""))
    connection.execute(text("""INSERT INTO qr_scan_logs
        (scan_type,entity_id,entity_no,operator_id,operation,notes)
        VALUES ('MAT',1,'MATERIAL-BASELINE',1,'QUERY','legacy sentinel')"""))


def owned_database_factory():
    source = make_url(settings.DATABASE_URL)
    if source.get_backend_name() != "postgresql" or not source.database:
        pytest.fail("QR migration acceptance requires PostgreSQL", pytrace=False)
    configured = source.set(drivername="postgresql+psycopg2")
    business_database = configured.database
    admin_engine = create_engine(configured, echo=False, poolclass=NullPool,
                                 isolation_level="AUTOCOMMIT", connect_args={"connect_timeout": 10})

    @contextmanager
    def factory():
        name = "qrtmp_" + uuid4().hex
        assert re.fullmatch(r"qrtmp_[a-f0-9]{32}", name) and name != business_database
        owned_oid = None
        engine = None
        try:
            try:
                with admin_engine.connect() as admin:
                    admin.exec_driver_sql(f'CREATE DATABASE "{name}"')
                    owned_oid = admin.execute(text("SELECT oid FROM pg_database WHERE datname=:name"),
                                             {"name": name}).scalar_one()
                engine = create_engine(configured.set(database=name), echo=False,
                                       pool_size=1, max_overflow=0, pool_pre_ping=True,
                                       connect_args={"connect_timeout": 10})
                with engine.connect() as connection:
                    assert connection.execute(text("SELECT current_database()")).scalar_one() == name
            except SQLAlchemyError as error:
                pytest.fail(f"Isolated QR database unavailable ({type(error).__name__}); no business writes",
                            pytrace=False)
            yield engine
        finally:
            if engine is not None:
                engine.dispose()
            if owned_oid is not None:
                # Only a database created in this invocation with the same OID is owned.
                with admin_engine.connect() as admin:
                    current_oid = admin.execute(text("SELECT oid FROM pg_database WHERE datname=:name"),
                                                {"name": name}).scalar_one_or_none()
                    if current_oid != owned_oid or name == business_database:
                        pytest.fail("Temporary QR database ownership changed; cleanup refused", pytrace=False)
                    admin.execute(text("SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                                       "WHERE datname=:name AND pid<>pg_backend_pid()"), {"name": name})
                    admin.exec_driver_sql(f'DROP DATABASE "{name}"')

    yield factory
    admin_engine.dispose()


@pytest.fixture(scope="module")
def qr_database_factory():
    yield from owned_database_factory()


