import pytest_asyncio
from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine


@pytest_asyncio.fixture
async def service_db(qr_service_engine):
    engine = create_async_engine(qr_service_engine.url.set(drivername="postgresql+asyncpg"),
                                 echo=False, poolclass=NullPool, connect_args={"timeout": 10})
    connection = None
    try:
        # Retry only establishing a connection, before opening a transaction.
        # No DDL/DML or test operation is replayed after an uncertain result.
        for attempt in range(3):
            try:
                connection = await engine.connect()
                break
            except (OSError, TimeoutError, SQLAlchemyError) as error:
                if attempt == 2:
                    pytest.fail(f"Isolated QR connection unavailable ({type(error).__name__})", pytrace=False)
        transaction = await connection.begin()
        try:
            async with AsyncSession(bind=connection, expire_on_commit=False,
                                    join_transaction_mode="create_savepoint") as session:
                yield session
        finally:
            await transaction.rollback()
    finally:
        if connection is not None:
            await connection.close()
        await engine.dispose()
