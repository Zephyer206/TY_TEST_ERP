/** Read-only acceptance for planned-date status and a normal business ledger. */
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require(process.argv[2] || 'playwright')
const base = process.env.ZEPHYR_TEST_URL || 'http://127.0.0.1:8080'
const output = path.resolve('runtime/acceptance/nonconforming-schedule')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, args: ['--disable-gpu', '--renderer-process-limit=2'], ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) })
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, locale: 'zh-CN', timezoneId: 'Asia/Shanghai' })
const page = await context.newPage(); page.setDefaultTimeout(15000)
const errors = [], passed = []
page.on('pageerror', error => errors.push(error.message))
const log = message => { passed.push(message); console.log(`PASS ${message}`) }
const drawer = () => page.locator('.quality-drawer:visible')
async function closeDetail() { await drawer().locator('.el-drawer__close-btn').click(); await drawer().waitFor({ state: 'hidden' }); await page.mouse.move(100, 150); await page.keyboard.press('Escape') }
try {
  const response = await context.request.get(`${base}/api/v1/nonconforming?company=tianyue`)
  assert.equal(response.status(), 200)
  const data = await response.json()
  assert.equal(data.records.length, 105)
  assert.equal(data.records.filter(row => row.status === 'processing').length, 9)
  assert.equal(data.records.filter(row => row.status === 'closed').length, 37)
  assert.equal(data.records.filter(row => row.status === 'pending_confirmation').length, 59)
  assert.equal(data.records.filter(row => row.plannedDate).length, 40)
  assert.ok(data.records.filter(row => row.plannedDate).every(row => row.plannedDate === row.importInfo.originalPlanned))
  assert.ok(data.records.filter(row => row.status === 'processing').every(row => row.importedProgress?.basis === 'source_planned_date' && !row.actualDate && !row.moldReady))
  assert.equal(data.records.filter(row => !row.quantityVerified).length, 6)
  log('数据库105条：9条处理中、37条已关闭、59条待确认；40条计划日期已登记，数量核对标志保留')
  await page.goto(`${base}/nonconforming`)
  await page.getByRole('button', { name: /^全部\s*105$/ }).waitFor()
  assert.equal(await page.locator('.quality-preview-notice,.quality-import-summary').count(), 0)
  assert.doesNotMatch(await page.locator('.quality-v1').innerText(), /原表|Excel|服务器数据库|localStorage/)
  assert.doesNotMatch(await page.locator('.quality-ledger thead').innerText(), /原表进度/)
  assert.match(await page.locator('.quality-stats').innerText(), /待确认[\s\S]*59[\s\S]*处理中[\s\S]*9[\s\S]*已完成[\s\S]*37/)
  await page.screenshot({ path: path.join(output, 'normal-ledger-desktop.png'), animations: 'disabled' })
  log('默认展示完整业务台账和状态统计，无导入概况、原表进度列及重复存储说明')
  await page.getByRole('button', { name: /^处理中\s*9$/ }).click()
  assert.match(await page.locator('.quality-toolbar-total').innerText(), /共 9 条/)
  await page.getByRole('button', { name: 'APG098A', exact: true }).click()
  await drawer().getByText('2026-10-19', { exact: true }).first().waitFor()
  assert.match(await drawer().locator('.quality-detail-heading').innerText(), /处理中/)
  assert.equal(await drawer().getByRole('button', { name: '提交品质验收', exact: true }).isDisabled(), true)
  const archive = drawer().locator('.quality-source-archive')
  assert.equal(await archive.getAttribute('open'), null)
  assert.equal(await archive.locator('.quality-workbook-origin').isVisible(), false)
  assert.equal(await drawer().locator('.quality-record-history').getAttribute('open'), null)
  await archive.locator('summary').first().focus(); await page.keyboard.press('Enter')
  assert.notEqual(await archive.getAttribute('open'), null)
  assert.equal(await archive.locator('.quality-workbook-origin').isVisible(), true)
  await archive.locator('summary').first().press('Enter')
  assert.equal(await archive.locator('.quality-workbook-origin').isVisible(), false)
  await closeDetail()
  log('处理中记录直接显示计划日期；来源与历史默认折叠、可用键盘展开，方案未完善时不能直接提交验收')
  await page.getByRole('button', { name: /^全部\s*105$/ }).click()
  await page.getByRole('button', { name: /^更多筛选/ }).click()
  assert.match(await page.locator('.quality-import-filters').innerText(), /全部记录/)
  await page.getByText('仅看数量待核对', { exact: true }).click()
  assert.match(await page.locator('.quality-toolbar-total').innerText(), /共 6 条/)
  await page.getByRole('button', { name: /^更多筛选/ }).click()
  assert.match(await page.getByRole('button', { name: /^更多筛选/ }).innerText(), /已筛选/)
  await page.getByRole('button', { name: /^更多筛选/ }).click()
  await page.getByText('仅看数量待核对', { exact: true }).click()
  await page.getByRole('button', { name: /^更多筛选/ }).click()
  await page.getByRole('tab', { name: '每周处理计划', exact: true }).click()
  const next = page.locator('.quality-week-column').nth(1)
  assert.equal(await next.locator('.quality-week-card').count(), 4)
  assert.match(await next.innerText(), /APG098A/)
  assert.equal(await page.locator('.quality-week-card .el-tag').filter({ hasText: '已关闭' }).count(), 0)
  log('更多筛选保留数量核对功能；计划日期进入周计划，下周4条任务可见，已完成记录不占执行任务')
  await page.getByRole('tab', { name: '不良品台账', exact: true }).click()
  await page.getByRole('button', { name: /^已关闭\s*37$/ }).click()
  assert.match(await page.locator('.quality-toolbar-total').innerText(), /共 37 条/)
  assert.match(await page.locator('.quality-ledger .el-table__body tr').first().innerText(), /2026-09-12/)
  await page.getByRole('button', { name: data.records.find(row => row.status === 'closed').partNo, exact: true }).first().click()
  assert.match(await drawer().innerText(), /实际完成时间[\s\S]*2026-09-12/)
  assert.equal(await drawer().getByRole('button', { name: '退回待确认', exact: true }).count(), 0)
  await closeDetail()
  await page.goto(`${base}/tooling/rework`)
  await page.getByRole('button', { name: '新增返工模', exact: true }).waitFor()
  assert.equal(await page.locator('.quality-preview-notice').count(), 0)
  await page.getByRole('button', { name: '新增返工模', exact: true }).click()
  await page.getByRole('dialog', { name: '新增返工模', exact: true }).getByRole('button', { name: '取消', exact: true }).click()
  log('37条已完成记录及完成日期保持正常显示，返工模页面同样去掉重复存储提示')
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'zh-CN', timezoneId: 'Asia/Shanghai' })
  const mobile = await mobileContext.newPage(); mobile.on('pageerror', error => errors.push(error.message))
  await mobile.goto(`${base}/nonconforming`)
  await mobile.getByRole('button', { name: /^处理中\s*9$/ }).waitFor()
  assert.equal(await mobile.locator('.quality-preview-notice,.quality-import-summary').count(), 0)
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await mobile.getByRole('button', { name: /^处理中\s*9$/ }).click()
  assert.match(await mobile.locator('.quality-toolbar-total').innerText(), /共 9 条/)
  await mobile.screenshot({ path: path.join(output, 'normal-ledger-mobile.png'), animations: 'disabled' })
  log('独立390px手机会话显示相同状态和日期，无整页横向溢出')
  assert.deepEqual(errors, [])
  await fs.writeFile(path.join(output, 'browser-report.json'), JSON.stringify({ base, browser: browser.version(), passed, errors }, null, 2))
} catch (error) {
  await page.screenshot({ path: path.join(output, 'failure.png'), animations: 'disabled' }).catch(() => {})
  throw error
} finally { await browser.close() }
