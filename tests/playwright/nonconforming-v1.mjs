async function screenshot(target, filename) {
  await target.waitForFunction(() => !Array.from(document.querySelectorAll('[class*="-enter-active"],[class*="-leave-active"]')).some(el => el.getClientRects().length))
  await target.waitForFunction(() => document.querySelectorAll('.el-message').length === 0)
  await target.screenshot({ path: path.join(output, filename), fullPage: true, animations: 'disabled' })
}
