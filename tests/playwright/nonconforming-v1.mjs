async function closeDrawer() { await currentDrawer().locator('.el-drawer__close-btn').click() }
async function inspect(note, close = false) {
  await currentDrawer().getByRole('button', { name: '品质验收', exact: true }).click()
  const checks = dialog('品质验收').locator('.quality-inspection-check')
  for (const check of await checks.all()) {
    await check.getByRole('textbox').fill('按确认标准核实通过')
    await check.getByText('通过', { exact: true }).click()
  }
  await dialog('品质验收').locator('.el-checkbox').filter({ hasText: '已核对本次提交的实物数量' }).click()
  await dialog('品质验收').getByPlaceholder('记录验收依据、结果或不通过原因').fill(note)
  await dialog('品质验收').getByRole('button', { name: close ? '验收通过并关闭' : '保存验收结果', exact: true }).click()
}
async function finishSteps() {
  const button = currentDrawer().getByRole('button', { name: '记录本步完成', exact: true })
  while (await button.count()) {
    await button.click()
    await dialog('记录本步完成').getByRole('textbox').fill('本步按已确认要求完成')
    await dialog('记录本步完成').getByRole('button', { name: '保存本步完成' }).click()
    await dialog('记录本步完成').waitFor({ state: 'hidden' })
  }
}

